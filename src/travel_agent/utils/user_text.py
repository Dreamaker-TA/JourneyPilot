"""「一串空白算不算一个值」—— **这个问题在全仓只由这里回答。**

三个入口各自收用户敲进来的一段文字，此前三处对空白给了三种答案：

* ``PATCH /users/{id}/preferences`` 拿到 ``"   "`` 时 **200 原样存入**，于是「我的偏好」
  那一屏上有一组偏好持有一个看不见的值；
* ``POST /users/{id}/memory/facts`` 先 ``strip()`` 再判真假，空白 **422**；
* 知识库入库数「去掉全部空白之后还剩几个字」，不够 **422**（``no_indexable_text``）。

同一个问题三种答案，就是这个仓最贵的那个形状（同一件事有三套取值）的文字版：
读的人无从知道自己这一处会拿到哪一种。规则收成一条 ——

    **空白不是一个值。** 一段文字有没有内容，看的是**去掉全部空白之后还剩几个字符**；
    一个只有空白的字符串不算内容，边界上一律 422，不许原样存、也不许静默变成空。

「还剩几个字符才够」是各字段自己的属性（记忆一句话 1 个字就够，一份资料 8 个字才算
有正文），所以**阈值不在这里**；这里只定**量法**与**判词**。
"""

from __future__ import annotations

__all__ = ["content_length", "is_blank"]


def content_length(text: str) -> int:
    """这段文字里有几个非空白字符。

    ``str.split()`` 不带参数时按**任意空白**切并丢掉空段，所以半角空格、制表符、换行、
    以及中文里最常误输入的全角空格 ``\\u3000`` 全部算空白 —— 这正是
    ``len(text.strip())`` 抓不住的那一类（``"a\\u3000b".strip()`` 是 3）。
    """

    return len("".join(text.split()))


def is_blank(text: str) -> bool:
    """这段文字一个非空白字符都没有 —— 它不是一个值。"""

    return content_length(text) == 0
